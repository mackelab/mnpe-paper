# Queue length observation indices in the x vector
Q_INDICES = [3, 4]


def transform_x(x: torch.Tensor) -> torch.Tensor:
    """
    Apply log1p to queue length observations to reduce skewness.

    Queue lengths have extreme right skew (median ~0.1, max ~10). Without
    this transform, z-scoring compresses the informative low-queue range
    into z in [-0.4, 0.3] while the tail stretches to z ~ 12. After log1p,
    the distribution is much more symmetric and z-scoring preserves
    resolution at the reference observation.

    Must be applied consistently to:
    - Training observations (x_all) before MNPE training
    - Reference observation (x_o) at inference time
    - SBC/ECE test observations (x_test)
    """
    x = x.clone()
    for i in Q_INDICES:
        x[:, i] = torch.log1p(x[:, i])
    return x


def stable_prior_mask(theta: torch.Tensor) -> torch.Tensor:
    """Return whether SBI-ordered parameter vectors lie in prior support."""
    theta = torch.as_tensor(theta)
    c_values = torch.as_tensor(C_VALUES, dtype=theta.dtype, device=theta.device)
    c1_raw, c2_raw = theta[..., 3], theta[..., 4]
    c1_idx, c2_idx = c1_raw.long(), c2_raw.long()
    valid_indices = (
        (c1_idx >= 0)
        & (c1_idx < N_C)
        & (c2_idx >= 0)
        & (c2_idx < N_C)
        & (c1_raw == c1_idx.to(theta.dtype))
        & (c2_raw == c2_idx.to(theta.dtype))
    )
    safe_c1_idx = c1_idx.clamp(0, N_C - 1)
    safe_c2_idx = c2_idx.clamp(0, N_C - 1)
    gamma, mu1, mu2 = theta[..., 0], theta[..., 1], theta[..., 2]
    positive = (gamma > 0) & (mu1 > 0) & (mu2 > 0)
    rho1 = gamma / (c_values[safe_c1_idx] * mu1)
    rho2 = gamma / (c_values[safe_c2_idx] * mu2)
    return (
        valid_indices
        & positive
        & (rho1 < MAX_UTILIZATION)
        & (rho2 < MAX_UTILIZATION)
    )


def _stable_prior_probability(num_quadrature_nodes: int = 64) -> float:
    """Normalize the product prior conditioned on joint queue stability."""
    nodes, weights = np.polynomial.hermite.hermgauss(num_quadrature_nodes)
    log_gamma = (
        np.log(GAMMA_MEDIAN) + np.sqrt(2.0) * GAMMA_SIGMA * nodes
    )
    gamma = np.exp(log_gamma)[:, None]
    lower_mu = gamma / (MAX_UTILIZATION * C_VALUES[None, :])
    p_mu1 = norm.sf(
        (np.log(lower_mu) - np.log(MU1_MEDIAN)) / MU1_SIGMA
    )
    p_mu2 = norm.sf(
        (np.log(lower_mu) - np.log(MU2_MEDIAN)) / MU2_SIGMA
    )
    stable_given_gamma = p_mu1.mean(axis=1) * p_mu2.mean(axis=1)
    return float(weights @ stable_given_gamma / np.sqrt(np.pi))


class _StableQueueSupport(constraints.Constraint):
    event_dim = 1

    def check(self, value: torch.Tensor) -> torch.Tensor:
        return stable_prior_mask(value)


class StableQueuePrior(Distribution):
    """Original product prior conditioned on both queues being stable."""

    arg_constraints: dict = {}
    has_rsample = False

    def __init__(self, base_prior: MultipleIndependent):
        self.base_prior = base_prior
        self.log_normalizer = math.log(_stable_prior_probability())
        super().__init__(
            batch_shape=torch.Size(),
            event_shape=torch.Size([5]),
            validate_args=False,
        )

    @property
    def support(self) -> constraints.Constraint:
        return _StableQueueSupport()

    def sample(self, sample_shape: torch.Size = torch.Size()) -> torch.Tensor:
        num_samples = torch.Size(sample_shape).numel()
        if num_samples == 0:
            return torch.empty(*sample_shape, self.event_shape[0])
        accepted = []
        num_accepted = 0
        while num_accepted < num_samples:
            remaining = num_samples - num_accepted
            proposals = self.base_prior.sample(
                (max(128, math.ceil(remaining / 0.8)),)
            )
            valid = proposals[stable_prior_mask(proposals)]
            accepted.append(valid)
            num_accepted += len(valid)
        samples = torch.cat(accepted, dim=0)[:num_samples]
        return samples.reshape(*sample_shape, self.event_shape[0])

    def log_prob(self, value: torch.Tensor) -> torch.Tensor:
        value = torch.as_tensor(value)
        accepted = stable_prior_mask(value)
        safe_value = value.clone()
        safe_value[..., 3:5] = safe_value[..., 3:5].round().clamp(0, N_C - 1)
        log_prob = self.base_prior.log_prob(safe_value) - self.log_normalizer
        return torch.where(
            accepted,
            log_prob,
            torch.full_like(log_prob, -torch.inf),
        )


def _build_base_sbi_prior() -> MultipleIndependent:
    """Build the unconditioned product prior used as rejection proposal."""
    prior_gamma = LogNormal(
        torch.log(torch.tensor([GAMMA_MEDIAN])), torch.tensor([GAMMA_SIGMA])
    )
    prior_mu1 = LogNormal(
        torch.log(torch.tensor([MU1_MEDIAN])), torch.tensor([MU1_SIGMA])
    )
    prior_mu2 = LogNormal(
        torch.log(torch.tensor([MU2_MEDIAN])), torch.tensor([MU2_SIGMA])
    )
    uniform_probs = (torch.ones(N_C) / N_C).unsqueeze(0)
    prior_c1 = Categorical(probs=uniform_probs)
    prior_c2 = Categorical(probs=uniform_probs)
    return MultipleIndependent(
        [prior_gamma, prior_mu1, prior_mu2, prior_c1, prior_c2]
    )


def build_sbi_prior() -> StableQueuePrior:
    """Stability-conditioned prior over [gamma, mu1, mu2, c1, c2]; c1, c2 index C_VALUES."""
    return StableQueuePrior(_build_base_sbi_prior())


def _compute_E_Q_pytensor(r, rho, c_val):
    """E[Q] for one M/M/c station in PyTensor, matching ``compute_E_Q`` exactly."""
    factorials = np.array([math.factorial(n) for n in range(c_val)])
    factorial_c = math.factorial(c_val)

    sum_terms = [r**n / factorials[n] for n in range(c_val)]
    sum_term = pt.sum(pt.stack(sum_terms))
    geom_term = (r**c_val / factorial_c) * (1.0 / (1.0 - rho + 1e-10))
    pi_0 = 1.0 / (sum_term + geom_term)

    E_Q = (r**c_val * rho) / (factorial_c * (1.0 - rho + 1e-10) ** 2) * pi_0
    return E_Q


def compute_E_Q(c: int, gamma: float, mu: float) -> float:
    """
    Compute E[Q] (expected number in queue) for an M/M/c station.

    Uses the same formula as ``_compute_E_Q_pytensor`` above, including its
    1e-10 epsilon. The epsilon is not cosmetic: it is what keeps the formula
    finite as rho approaches 1, and the two implementations must share it or the
    simulator and the PyMC likelihood would disagree near the stability boundary.

    Parameters
    ----------
    c : int
        Number of servers
    gamma : float
        Arrival rate
    mu : float
        Service rate per server

    Returns
    -------
    float
        Expected queue length E[Q]
    """
    r = gamma / mu
    rho = gamma / (c * mu)

    factorials = np.array([math.factorial(n) for n in range(c)])
    factorial_c = math.factorial(c)

    sum_term = sum(r**n / factorials[n] for n in range(c))
    geom_term = (r**c / factorial_c) * (1.0 / (1.0 - rho + 1e-10))
    pi_0 = 1.0 / (sum_term + geom_term)

    E_Q = (r**c * rho) / (factorial_c * (1.0 - rho + 1e-10) ** 2) * pi_0
    return E_Q


def build_pymc_model():
    """
    Build the canonical mixed PyMC queue model.

    The model is the unconditioned product prior; ``generate_training_data``
    obtains the stability-conditioned target by rejecting parameter vectors
    outside support.

    Returns
    -------
    pm.Model
        The generative model with all RVs as free variables.
    """
    with pm.Model() as model:
        c1_idx = pm.Categorical("c1_idx", p=np.ones(N_C) / N_C)
        c2_idx = pm.Categorical("c2_idx", p=np.ones(N_C) / N_C)

        gamma = pm.LogNormal("gamma", mu=np.log(GAMMA_MEDIAN), sigma=GAMMA_SIGMA)
        mu1 = pm.LogNormal("mu1", mu=np.log(MU1_MEDIAN), sigma=MU1_SIGMA)
        mu2 = pm.LogNormal("mu2", mu=np.log(MU2_MEDIAN), sigma=MU2_SIGMA)

        # Traffic equations
        lambda1 = gamma
        lambda2 = gamma

        pm.Poisson(
            "n_arrivals_obs",
            mu=gamma * T,
        )
        pm.Poisson(
            "n_completions_1_obs",
            mu=lambda1 * T,
        )
        pm.Poisson(
            "n_completions_2_obs",
            mu=lambda2 * T,
        )

        # Queue lengths: E[Q] via M/M/c, branching on c1_idx/c2_idx
        r1 = lambda1 / mu1
        E_Q1_list = [
            _compute_E_Q_pytensor(r1, lambda1 / (c * mu1), c) for c in C_VALUES
        ]
        E_Q1 = E_Q1_list[-1]
        for i in range(N_C - 2, -1, -1):
            E_Q1 = pt.switch(pt.eq(c1_idx, i), E_Q1_list[i], E_Q1)

        r2 = lambda2 / mu2
        E_Q2_list = [
            _compute_E_Q_pytensor(r2, lambda2 / (c * mu2), c) for c in C_VALUES
        ]
        E_Q2 = E_Q2_list[-1]
        for i in range(N_C - 2, -1, -1):
            E_Q2 = pt.switch(pt.eq(c2_idx, i), E_Q2_list[i], E_Q2)

        pm.TruncatedNormal(
            "queue_length_1_obs", mu=E_Q1, sigma=OBSERVATION_NOISE, lower=0,
        )
        pm.TruncatedNormal(
            "queue_length_2_obs", mu=E_Q2, sigma=OBSERVATION_NOISE, lower=0,
        )

    return model


def build_pymc_marginalized_model(observations: dict):
    """Build the exact continuous PyMC target with ``c1,c2`` marginalized.

    The categorical configuration sum includes the stability indicator inside
    each term. This is equivalent to the stability-conditioned mixed model up
    to its single global prior normalizer, which cancels in the posterior.
    """
    with pm.Model() as model:
        gamma = pm.LogNormal(
            "gamma", mu=np.log(GAMMA_MEDIAN), sigma=GAMMA_SIGMA
        )
        mu1 = pm.LogNormal("mu1", mu=np.log(MU1_MEDIAN), sigma=MU1_SIGMA)
        mu2 = pm.LogNormal("mu2", mu=np.log(MU2_MEDIAN), sigma=MU2_SIGMA)

        pm.Poisson(
            "n_arrivals_obs",
            mu=gamma * T,
            observed=observations["n_arrivals"],
        )
        pm.Poisson(
            "n_completions_1_obs",
            mu=gamma * T,
            observed=observations["n_completions_1"],
        )
        pm.Poisson(
            "n_completions_2_obs",
            mu=gamma * T,
            observed=observations["n_completions_2"],
        )

        config_terms = []
        log_config_prior = -2.0 * np.log(N_C)
        for c1 in C_VALUES:
            rho1 = gamma / (int(c1) * mu1)
            eq1 = _compute_E_Q_pytensor(gamma / mu1, rho1, int(c1))
            log_q1 = pm.logp(
                pm.TruncatedNormal.dist(
                    mu=eq1, sigma=OBSERVATION_NOISE, lower=0
                ),
                observations["queue_length_1"],
            )
            for c2 in C_VALUES:
                rho2 = gamma / (int(c2) * mu2)
                eq2 = _compute_E_Q_pytensor(gamma / mu2, rho2, int(c2))
                log_q2 = pm.logp(
                    pm.TruncatedNormal.dist(
                        mu=eq2, sigma=OBSERVATION_NOISE, lower=0
                    ),
                    observations["queue_length_2"],
                )
                stable = (
                    (rho1 < MAX_UTILIZATION)
                    & (rho2 < MAX_UTILIZATION)
                )
                config_terms.append(
                    log_config_prior
                    + log_q1
                    + log_q2
                    + pt.switch(stable, 0.0, -np.inf)
                )

        pm.Potential(
            "marginal_queue_likelihood",
            pt.logsumexp(pt.stack(config_terms)),
        )

    return model


def configuration_probabilities_numpy(
    gamma: np.ndarray,
    mu1: np.ndarray,
    mu2: np.ndarray,
    observations: dict,
) -> tuple[list[tuple[int, int]], np.ndarray]:
    """Evaluate exact joint configuration probabilities per continuous draw."""
    gamma = np.asarray(gamma)
    mu1 = np.asarray(mu1)
    mu2 = np.asarray(mu2)
    configs = [
        (int(c1), int(c2)) for c1 in C_VALUES for c2 in C_VALUES
    ]
    log_weights = np.full((len(gamma), len(configs)), -np.inf)
    log_config_prior = -2.0 * np.log(N_C)

    for j, (c1, c2) in enumerate(configs):
        rho1 = gamma / (c1 * mu1)
        rho2 = gamma / (c2 * mu2)
        stable = (
            (rho1 < MAX_UTILIZATION)
            & (rho2 < MAX_UTILIZATION)
        )
        if not stable.any():
            continue

        eq1 = compute_E_Q(c1, gamma[stable], mu1[stable])
        eq2 = compute_E_Q(c2, gamma[stable], mu2[stable])
        log_q1 = truncnorm.logpdf(
            observations["queue_length_1"],
            a=-eq1 / OBSERVATION_NOISE,
            b=np.inf,
            loc=eq1,
            scale=OBSERVATION_NOISE,
        )
        log_q2 = truncnorm.logpdf(
            observations["queue_length_2"],
            a=-eq2 / OBSERVATION_NOISE,
            b=np.inf,
            loc=eq2,
            scale=OBSERVATION_NOISE,
        )
        log_weights[stable, j] = log_config_prior + log_q1 + log_q2

    log_norm = logsumexp(log_weights, axis=1, keepdims=True)
    if not np.isfinite(log_norm).all():
        raise FloatingPointError(
            "At least one continuous draw has no stable configuration"
        )
    return configs, np.exp(log_weights - log_norm)


def generate_training_data(
    n_samples: int, seed: int = 42,
) -> tuple[torch.Tensor, torch.Tensor]:
    """
    Generate (theta, x) training pairs via PyMC prior predictive sampling.

    Uses exact rejection sampling to condition the original product prior on
    joint stability. Observations for accepted parameters come from the PyMC
    prior-predictive model. Exactly ``n_samples`` valid pairs are returned.

    Parameters
    ----------
    n_samples : int
        Number of stable training pairs to return.
    seed : int
        Random seed for reproducibility.

    Returns
    -------
    theta : torch.Tensor of shape (n_valid, 5)
        Parameter tensor [gamma, mu1, mu2, c1_idx, c2_idx].
    x : torch.Tensor of shape (n_valid, 5)
        Observation tensor [n_arrivals, n_comp_1, n_comp_2, q1, q2].
    """
    model = build_pymc_model()

    seed_rng = np.random.default_rng(seed)
    theta_chunks, x_chunks = [], []
    n_accepted = 0
    n_proposed = 0

    while n_accepted < n_samples:
        remaining = n_samples - n_accepted
        proposal_batch = min(100_000, max(256, math.ceil(remaining / 0.8)))
        batch_seed = int(seed_rng.integers(0, np.iinfo(np.int32).max))

        with model:
            prior_pred = pm.sample_prior_predictive(
                draws=proposal_batch,
                random_seed=batch_seed,
            )

        theta_batch = np.column_stack([
            prior_pred.prior["gamma"].values.flatten(),
            prior_pred.prior["mu1"].values.flatten(),
            prior_pred.prior["mu2"].values.flatten(),
            prior_pred.prior["c1_idx"].values.flatten(),
            prior_pred.prior["c2_idx"].values.flatten(),
        ])
        x_batch = np.column_stack([
            prior_pred.prior["n_arrivals_obs"].values.flatten(),
            prior_pred.prior["n_completions_1_obs"].values.flatten(),
            prior_pred.prior["n_completions_2_obs"].values.flatten(),
            prior_pred.prior["queue_length_1_obs"].values.flatten(),
            prior_pred.prior["queue_length_2_obs"].values.flatten(),
        ])

        stable = stability_mask_numpy(theta_batch)
        if not np.isfinite(x_batch[stable]).all():
            raise FloatingPointError(
                "PyMC generated non-finite observations for stable parameters"
            )
        theta_chunks.append(theta_batch[stable])
        x_chunks.append(x_batch[stable])
        n_accepted += int(stable.sum())
        n_proposed += proposal_batch

    theta_np = np.concatenate(theta_chunks, axis=0)[:n_samples]
    x_np = np.concatenate(x_chunks, axis=0)[:n_samples]
    assert stability_mask_numpy(theta_np).all()
    print(
        f"  Stability-conditioned prior: returned {n_samples:,} samples from "
        f"{n_proposed:,} proposals "
        f"({n_accepted / n_proposed:.1%} stable)"
    )

    return (
        torch.tensor(theta_np, dtype=torch.float32),
        torch.tensor(x_np, dtype=torch.float32),
    )


def simulator(theta: np.ndarray, seed: int = None) -> np.ndarray:
    """
    Simulator function: maps parameters to observations.

    For batch training data generation, prefer generate_training_data() which
    uses pm.sample_prior_predictive() for guaranteed PyMC consistency.

    This function is kept for single evaluations (e.g., generating reference
    observations) where the numpy E[Q] formula is equivalent and much faster.

    Parameters
    ----------
    theta : np.ndarray
        Parameter array of shape (5,) or (n_samples, 5) with columns:
        [gamma, mu1, mu2, c1_index, c2_index]

        Note: c1_index, c2_index are 0-indexed (0..N_C-1) corresponding to C_VALUES servers

    seed : int, optional
        Random seed for reproducibility

    Returns
    -------
    x : np.ndarray
        Observation array of shape (5,) or (n_samples, 5) with columns:
        [n_arrivals, n_completions_1, n_completions_2, queue_length_1, queue_length_2]

    Returns NaN outside the stability-conditioned prior support.
    """
    single_sample = theta.ndim == 1
    if single_sample:
        theta = theta.reshape(1, -1)

    n_samples = theta.shape[0]
    x = np.zeros((n_samples, 5))

    rng = np.random.default_rng(seed)

    for i in range(n_samples):
        gamma, mu1, mu2, c1_index, c2_index = theta[i]

        c1 = C_VALUES[int(c1_index)]
        c2 = C_VALUES[int(c2_index)]

        rho1 = gamma / (c1 * mu1)
        rho2 = gamma / (c2 * mu2)
        if rho1 >= MAX_UTILIZATION or rho2 >= MAX_UTILIZATION:
            x[i] = np.nan
            continue

        E_Q1 = compute_E_Q(c1, gamma, mu1)
        E_Q2 = compute_E_Q(c2, gamma, mu2)

        # For stable tandem networks, throughput = arrival rate = gamma
        n_arrivals = rng.poisson(gamma * T)
        n_completions_1 = rng.poisson(gamma * T)
        n_completions_2 = rng.poisson(gamma * T)

        a1 = -E_Q1 / OBSERVATION_NOISE  # lower=0 in std units
        a2 = -E_Q2 / OBSERVATION_NOISE
        q1 = truncnorm.rvs(
            a=a1, b=np.inf, loc=E_Q1, scale=OBSERVATION_NOISE, random_state=rng,
        )
        q2 = truncnorm.rvs(
            a=a2, b=np.inf, loc=E_Q2, scale=OBSERVATION_NOISE, random_state=rng,
        )

        x[i] = [n_arrivals, n_completions_1, n_completions_2, q1, q2]

    if single_sample:
        x = x.reshape(-1)

    return x


