C2_TRUE_IDX = int(np.where(C_VALUES == C2_TRUE)[0][0])
THETA_TRUE_SBI = np.array([GAMMA_TRUE, MU1_TRUE, MU2_TRUE, C1_TRUE_IDX, C2_TRUE_IDX])


def generate_reference_observation(seed: int = 42) -> dict:
    """
    Generate a reference observation using true parameters.

    This ensures both PyMC and MNPE use the exact same observed data.

    Parameters
    ----------
    seed : int
        Random seed for reproducibility

    Returns
    -------
    dict
        Dictionary with keys:
        - 'x_array': observation as numpy array [n_arrivals, n_completions_1, n_completions_2, queue_length_1, queue_length_2]
        - 'x_dict': observation as dict with named keys
        - 'stable', 'rho1', 'rho2': stability info
        - Individual observation values as top-level keys
    """
    x_array = simulator(THETA_TRUE_SBI, seed=seed)

    x_dict = {
        'n_arrivals': x_array[0],
        'n_completions_1': x_array[1],
        'n_completions_2': x_array[2],
        'queue_length_1': x_array[3],
        'queue_length_2': x_array[4],
    }

    # Compute metadata for compatibility with downstream code
    rho1 = GAMMA_TRUE / (C1_TRUE * MU1_TRUE)
    rho2 = GAMMA_TRUE / (C2_TRUE * MU2_TRUE)

    return {
        'x_array': x_array,
        'x_dict': x_dict,
        'n_arrivals': x_array[0],
        'n_completions_1': x_array[1],
        'n_completions_2': x_array[2],
        'queue_length_1': x_array[3],
        'queue_length_2': x_array[4],
        'stable': True,
        'rho1': rho1,
        'rho2': rho2,
    }


